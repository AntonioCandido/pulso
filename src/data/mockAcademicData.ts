export function getPulsoImparDisciplines(weights: FormulaWeights = DEFAULT_WEIGHTS): DisciplineMetric[] {
  return RAW_PULSO_IMPAR_DISCIPLINES.map((d) => {
    const lhi = calculateLHI(
      d.learningScore,
      d.attendanceRate,
      d.failureRate,
      d.lmsAdherenceRate,
      weights.lhi
    );
    const ars = calculateARS(
      d.failureRate,
      d.attendanceRate,
      d.learningScore,
      d.dropoutRiskRate,
      weights.ars
    );
    return {
      ...d,
      lhi,
      ars,
      lhiStatus: getLHIStatus(lhi),
      arsLevel: getARSLevel(ars),
      recommendedAction: getRecommendedPedagogicalAction({ ...d, lhi, ars } as DisciplineMetric),
    };
  });
}

